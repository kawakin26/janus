"""
API 共通ユーティリティ。

ページパスの正規化（normalize_path）を提供する。ページ CRUD（タスク 5.1）と
子ページ一覧（タスク 5.2）の両方で共用し、ユーザー入力のパスを安全な正規形へ
畳み込む。純粋関数として DB・リクエストに依存しない。
"""


def normalize_path(raw: str | None) -> str:
    """ユーザー入力のページパスを安全な正規形に変換する。

    正規化規則（design.md 3 章「末尾スラッシュ正規化」・要件 2-7、および
    「予期せぬ値を安全に扱う」方針に基づく）:

    1. 入力整形: 文字列化し前後の空白を除去する。None は空文字として扱う。
    2. セグメント分解と除去: "/" で分割し、空セグメント（過剰スラッシュ "//"
       由来）・"."（カレント）・".."（親参照）をすべて落とす。".." は親への
       遡上を許さず単純に除去し、相対参照によるディレクトリトラバーサルを
       無効化する（安全側）。各セグメントは前後空白を strip する。
    3. 再構築: 残ったセグメントを "/" で連結し、先頭に "/" を 1 つ付与する
       （絶対パス表現で統一。例 "docs/intro" → "/docs/intro"）。
    4. 末尾スラッシュ除去: 末尾に "/" は付けない（"/docs/intro/" → "/docs/intro"）。
    5. ルート/空の扱い: 整形後にセグメントが 0 個になった場合（入力が ""・"/"・
       "///"・".."・"." 等）は、ルートを表す正規値として "/" を返す（空文字は
       返さない）。これにより一意性判定が破綻しない。

    補足（2 つの「ルート」概念の違い）:
      - ページ本体としての path "/": ルートページそのもの。作成・取得の対象に
        なりうる正規値。
      - listChildren の「ルート/空」: parent が "/" のとき、第 1 階層（トップ
        レベル）の子一覧を返す意味で使う（views.PageChildrenView 参照）。
      この 2 用途は値としては同じ "/" だが意味が異なるため、呼び出し側で区別する。
    """
    # 1. None は空文字扱い。文字列化して前後空白を除去。
    text = "" if raw is None else str(raw).strip()

    # 2. "/" 分割し、空・"."・".." を落とす。各セグメントは strip。
    segments = []
    for segment in text.split("/"):
        segment = segment.strip()
        if segment in ("", ".", ".."):
            continue
        segments.append(segment)

    # 5. セグメントが無ければルート "/" を返す。
    if not segments:
        return "/"

    # 3-4. 先頭 "/" を付け、末尾 "/" は付けない。
    return "/" + "/".join(segments)


def ancestor_paths(path: str) -> list[str]:
    """正規化済み path の祖先パス列を、自身を含め近い順に返す。

    導出規則（design.md 3.4 章「祖先パスの導出」・権限合成の階層的近さ
    （3.2 ステップ 3）に基づく）:

    1. 前提: 入力は normalize_path 済みの絶対パス（先頭 "/"・末尾 "/" なし）。
       DB 固有機能に依存しない純粋な文字列処理のみを行う。
    2. 分解: path を "/" で分割し、空セグメント（ルート由来）を落として
       セグメント列を得る（normalize_path と同じ分解観点）。
    3. 構築: 自身（最も長い＝最も近い）から順に末尾セグメントを 1 つずつ
       削り、各段の絶対パスを近い順に並べる。最後に必ずルート "/" を
       最遠の祖先として付与する。
    4. ルート境界: path が "/"（ルート自身）の場合はセグメントが 0 個のため、
       ルートは自身のみを祖先に持つ正規値として ["/"] を返す（NIT-1）。

    例:
      - ancestor_paths("/docs/intro") == ["/docs/intro", "/docs", "/"]
      - ancestor_paths("/docs") == ["/docs", "/"]
      - ancestor_paths("/") == ["/"]
    """
    # 2. "/" 分割し、空セグメント（先頭 "/" やルート由来）を落とす。
    segments = [segment for segment in path.split("/") if segment]

    # 3. 自身から順に末尾を削り、近い順の絶対パス列を作る。
    ancestors = [
        "/" + "/".join(segments[:depth])
        for depth in range(len(segments), 0, -1)
    ]

    # 3-4. 最遠の祖先として常にルートを付ける（ルート自身なら ["/"] のみ）。
    ancestors.append("/")
    return ancestors
